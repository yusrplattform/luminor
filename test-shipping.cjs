const assert = require('node:assert/strict');
const { calculate } = require('./shipping.js');
const a = 'منتج - 4.500 ر.ع / 44 ر.س', b = 'زيت - 5.000 ر.ع / 49 ر.س';
const gulf = calculate([a, b], 'OM', {}).lines.join('\n');
assert.match(gulf, /إجمالي المنتجات فقط: 9\.500 ر\.ع/);
assert.match(gulf, /٧ ر\.ع/);
assert.match(gulf, /٩ ر\.ع/);
assert.match(gulf, /واتساب/);
assert.match(gulf, /لا يشمل الجمارك/);
assert.doesNotMatch(gulf, /الإجمالي: /);
const international = calculate([a], 'other', {}).lines.join('\n');
assert.match(international, /إجمالي المنتجات فقط: 4\.500 ر\.ع/);
assert.match(international, /يُؤكدان عبر واتساب/);
assert.doesNotMatch(international, /٧ ر\.ع/);
assert.match(calculate(['unknown'], 'OM', {}).lines.join('\n'), /مجموع المنتجات غير متوفر/);
console.log('Shipping summary checks passed');
